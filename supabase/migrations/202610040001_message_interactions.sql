create table public.message_reactions (
 message_id uuid not null references public.messages(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 emoji text not null references aedrova_private.reaction_emoji(emoji),
 primary key(message_id,user_id,emoji)
);
alter table public.message_reactions enable row level security;
revoke all on public.message_reactions from public,anon,authenticated;
grant select on public.message_reactions to authenticated;
create policy reactions_read on public.message_reactions for select to authenticated using (
 exists(select 1 from public.messages m where m.id=message_id
 and m.unsent_at is null and aedrova_private.can_read_channel(m.channel_id))
);
create function public.set_message_reaction(p_message uuid,p_emoji text,p_present boolean)
returns void language plpgsql security definer set search_path='' as $$
declare u uuid:=aedrova_private.require_user(); w uuid; m public.messages;
begin
 select c.workspace_id into w from public.messages x join public.channels c on c.id=x.channel_id
 where x.id=p_message;
 perform 1 from public.workspaces where id=w for update;
 select * into m from public.messages where id=p_message for update;
 if m.id is null or m.unsent_at is not null or not aedrova_private.can_read_channel(m.channel_id)
 or coalesce(aedrova_private.member_role(w),'') not in ('owner','admin','member')
 then raise exception 'Not allowed' using errcode='42501'; end if;
 if p_present is null or not exists(select 1 from aedrova_private.reaction_emoji where emoji=p_emoji)
 then raise exception 'Choose a valid emoji' using errcode='22023'; end if;
 perform aedrova_private.check_user_budget('reaction',120,60);
 if p_present then
 if not exists(select 1 from public.message_reactions where message_id=p_message and emoji=p_emoji)
 and (select count(distinct emoji) from public.message_reactions where message_id=p_message)>=64
 then raise exception 'Reaction limit reached' using errcode='22023'; end if;
 insert into public.message_reactions values(p_message,u,p_emoji) on conflict do nothing;
 else
 delete from public.message_reactions where message_id=p_message and user_id=u and emoji=p_emoji;
 end if;
 -- Content-free notifications only, same private recipients as ordinary messages.
 for u in select wm.user_id from public.workspace_members wm
 where wm.workspace_id=w and ((not (select private from public.channels where id=m.channel_id)
 and wm.role<>'guest') or exists(select 1 from public.channel_members cm
 where cm.channel_id=m.channel_id and cm.user_id=wm.user_id)) loop
 perform realtime.send('{}'::jsonb,'refresh','user:'||u::text,true);
 end loop;
end $$;
create function public.unsend_message(p_message uuid) returns void
language plpgsql security definer set search_path='' as $$
declare u uuid:=aedrova_private.require_user(); w uuid; m public.messages;
begin
 select c.workspace_id into w from public.messages x join public.channels c on c.id=x.channel_id
 where x.id=p_message;
 perform 1 from public.workspaces where id=w for update;
 select * into m from public.messages where id=p_message for update;
 if m.id is null or m.sender_id is distinct from u or not aedrova_private.can_read_channel(m.channel_id)
 or coalesce(aedrova_private.member_role(w),'') not in ('owner','admin','member')
 then raise exception 'Not allowed' using errcode='42501'; end if;
 if m.unsent_at is not null then return; end if;
 perform aedrova_private.check_user_budget('unsend',60,60);
 delete from public.context_decisions where message_id=p_message;
 delete from public.attachments where message_id=p_message;
 delete from public.message_reactions where message_id=p_message;
 -- Preserve thread references, erase body, and invalidate any collected build context.
 update public.messages set body='Message unsent.',unsent_at=clock_timestamp() where id=p_message;
end $$;
create trigger message_unsend_notification after update of unsent_at on public.messages
 for each row execute function aedrova_private.notify_message();
create function public.message_interactions(p_ids uuid[]) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 perform aedrova_private.require_user();
 if coalesce(cardinality(p_ids),0)>100 then raise exception 'Too many messages' using errcode='22023'; end if;
 return coalesce((select jsonb_agg(jsonb_build_object('id',m.id,'body',m.body,'unsent_at',m.unsent_at,
 'reactions',coalesce((select jsonb_agg(jsonb_build_object('emoji',g.emoji,'count',g.n,'mine',g.mine)
 order by g.emoji) from (select r.emoji,count(*) n,bool_or(r.user_id=auth.uid()) mine
 from public.message_reactions r where r.message_id=m.id and m.unsent_at is null group by r.emoji) g),
 '[]'::jsonb))) from public.messages m where m.id=any(p_ids)
 and aedrova_private.can_read_channel(m.channel_id)), '[]'::jsonb);
end $$;
revoke all on function public.set_message_reaction(uuid,text,boolean),public.unsend_message(uuid),
 public.message_interactions(uuid[]) from public,anon;
grant execute on function public.set_message_reaction(uuid,text,boolean),public.unsend_message(uuid),
 public.message_interactions(uuid[]) to authenticated;
commit;
